def icon(name, palette, rows):
    assert len(rows) == 16 and all(len(r) == 16 for r in rows), (name, [len(r) for r in rows])
    out = ['kind = icon', '[palette]'] + [f'{k} = {v}' for k, v in palette.items()] + ['[icon]'] + rows
    (ART / f'icon_{name}.txt').write_text('\n'.join(out) + '\n')


